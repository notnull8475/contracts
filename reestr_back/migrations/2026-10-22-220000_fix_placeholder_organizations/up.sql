-- Договоры, при импорте привязанные к организации-заглушке «Не указано», у которых
-- контрагент однозначно определяется по адресу: в справочнике есть ровно одна
-- организация с тем же фактическим адресом.
--
--   55/15Г   420021 Казань, ул. Сары Садыковой, д.49      → ООО "Коршай"
--   59/1-15  Нижнекамск, тер. Промзона, здание А-12а      → ООО "ГЕМОНТ"
--   3159262  443030 Самара, Комсомольская пл., д.1         → ОАО "Российские железные дороги"
--
-- Остальные договоры на заглушке адреса либо не имеют, либо он не совпадает ни с
-- одной организацией — их оставляем, контрагента восстановить неоткуда.

UPDATE contract c
SET organization_id = o.id
FROM organization o, organization placeholder
WHERE placeholder.id = c.organization_id
  AND placeholder.short_name_with_opf ILIKE 'не указано%'
  AND (
        (c.number = '55/15Г'  AND o.short_name_with_opf = 'ООО " Коршай"')
     OR (c.number = '59/1-15' AND o.short_name_with_opf = 'ООО "ГЕМОНТ"')
     OR (c.number = '3159262' AND o.short_name_with_opf = 'ОАО "Российские железные дороги"')
  );
